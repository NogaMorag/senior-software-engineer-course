-- Chapter 12 schema: the products table from chapter 10, plus updated_at, and 2,000 rows.
-- The tests apply it to a private schema; the stampede demo applies it to public.
DROP TABLE IF EXISTS products;

CREATE TABLE products (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    price_cents bigint NOT NULL CHECK (price_cents > 0),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

INSERT INTO products (id, name, price_cents)
SELECT i, 'Product ' || i, 500 + (i * 37) % 20000
FROM generate_series(1, 2000) AS i;
