-- Chapter 10 schema: customers, products, orders, order_items.
-- Only primary keys and the constraints a real schema would have. No extra indexes:
-- adding them is the exercise. Note that PostgreSQL does NOT index foreign keys for you.
DROP TABLE IF EXISTS order_items, orders, products, customers;

CREATE TABLE customers (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      text NOT NULL UNIQUE,
    name       text NOT NULL,
    country    text NOT NULL,
    created_at timestamptz NOT NULL
);

CREATE TABLE products (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    price_cents bigint NOT NULL CHECK (price_cents > 0)
);

CREATE TABLE orders (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES customers (id),
    status      text NOT NULL CHECK (status IN ('pending', 'paid', 'shipped', 'delivered', 'cancelled')),
    total_cents bigint NOT NULL,
    created_at  timestamptz NOT NULL
);

CREATE TABLE order_items (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    bigint NOT NULL REFERENCES orders (id),
    product_id  bigint NOT NULL REFERENCES products (id),
    quantity    int NOT NULL CHECK (quantity > 0),
    price_cents bigint NOT NULL
);
